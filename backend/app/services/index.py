"""
Индекс дефицита тени микрорайона (shade_deficit_index), 0..100.

Как объяснять жюри
------------------
Индекс отвечает на вопрос акимата: «Куда в первую очередь ставить навесы, фонтанчики
и сажать деревья?» Чем выше индекс, тем жарче и беззащитнее микрорайон для пешехода.
Он складывается из четырёх факторов, у каждого свой вес:

  40 % · heat_index_base        — насколько район нагревается сам по себе: плотная застройка,
                                  асфальт, удалённость от моря (0..1, модельная оценка;
                                  в перспективе — спутниковая температура поверхности Landsat).
  25 % · (1 − green_ratio)      — доля территории без зелени: чем меньше деревьев, тем меньше тени.
  20 % · открытые заявки        — голос жителей: сколько незакрытых жалоб на жару
                                  (new / in_review / planned); 12 и больше — максимум (насыщение).
  15 % · (1 − плотность охлаждения) — сколько точек охлаждения (остановки с кондиционером,
                                  парки, набережная, фонтанчики, аптеки) на км², нормировано
                                  по району-максимуму.

Почему такие веса: физика нагрева (40 + 25 = 65 %) — основа, её нельзя «перекричать» жалобами;
заявки (20 %) делают индекс живым — новая жалоба сразу поднимает район в рейтинге;
инфраструктура (15 %) показывает, где уже есть куда спрятаться.

Заявки нормируются по фиксированному порогу насыщения (12 открытых = 1.0), а не по району-лидеру:
так каждая новая жалоба поднимает индекс своего района, даже если он уже самый проблемный
(при нормировке «по максимуму» лидер упирался бы в 1.0 и не реагировал — нашли это на прод-проверке).
Плотность точек охлаждения нормируется по району-максимуму: важна относительная обеспеченность.

Функция чистая (без БД), поэтому формулу легко проверить тестом и пересчитать вручную.
"""
from dataclasses import dataclass

WEIGHTS = {"heat": 0.40, "no_green": 0.25, "reports": 0.20, "no_cooling": 0.15}
REPORTS_SATURATION = 12  # столько открытых заявок и больше = максимальный вклад фактора


@dataclass(frozen=True)
class DistrictFactors:
    id: int
    heat_index_base: float   # 0..1
    green_ratio: float       # 0..1
    open_reports: int        # незакрытые заявки
    cooling_density: float   # точек охлаждения на км²


def _clamp01(v: float) -> float:
    return max(0.0, min(1.0, v))


def shade_deficit_index(districts: list[DistrictFactors]) -> dict[int, dict]:
    """
    Возвращает {district_id: {"index": 0..100, "components": {...}}}.
    components — вклад каждого фактора в баллах; их сумма равна index (удобно показывать в UI).
    """
    max_density = max((d.cooling_density for d in districts), default=0.0) or 1.0

    result = {}
    for d in districts:
        factors = {
            "heat": _clamp01(d.heat_index_base),
            "no_green": 1 - _clamp01(d.green_ratio),
            "reports": min(d.open_reports, REPORTS_SATURATION) / REPORTS_SATURATION,
            "no_cooling": 1 - d.cooling_density / max_density,
        }
        components = {k: round(100 * WEIGHTS[k] * v, 1) for k, v in factors.items()}
        result[d.id] = {"index": round(sum(100 * WEIGHTS[k] * v for k, v in factors.items()), 1),
                        "components": components}
    return result
